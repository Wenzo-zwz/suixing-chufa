import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { createAppServer } from '../prototype/server.mjs';
import { DESTINATIONS } from '../prototype/catalog.mjs';
const { chromium } = createRequire(import.meta.url)('playwright');
const server = createAppServer();
await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const action = (p,name) => p.locator(`[data-action="${name}"]`).first();
const screen = (p,value) => p.waitForFunction(v => document.body.dataset.screen === v,value);
const browser = await chromium.launch({channel:'msedge',headless:true});
const errors=[],checks=[];
try {
  const context = await browser.newContext({viewport:{width:390,height:844}});
  await context.addInitScript(() => {
    const old = {id:'changsha',name:'长沙',description:'旧版示例内容',localBudget:{min:180,max:380}};
    if (!localStorage.getItem('roam-preview-v1')) localStorage.setItem('roam-preview-v1',JSON.stringify({saved:[old],journeys:[{id:'kept-journey',destination:old,status:'completed'}],history:[{destination:old,drawId:'kept-draw'}]}));
  });
  const page = await context.newPage(); page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base); await screen(page,'home');
  const cityCount = DESTINATIONS.filter(item => item.kind === 'city').length;
  const spotCount = DESTINATIONS.filter(item => item.kind === 'spot').length;
  assert.match(await page.locator('[data-catalog-coverage]').innerText(),new RegExp(`${cityCount}.*${spotCount}`));
  const restored = await page.evaluate(()=>JSON.parse(localStorage.getItem('roam-preview-v1')));
  assert.equal(restored.saved[0].localBudget,null); assert.ok(restored.saved[0].sources.length);
  assert.equal(restored.journeys[0].id,'kept-journey'); assert.equal(restored.journeys[0].status,'completed');
  assert.ok(restored.history[0].destination.foodGuide.length);
  checks.push('new coverage and old collection/journey/history upgrade');
  async function draw(name) {
    await page.locator('[data-action="go"][data-screen="home"]').first().click();
    await page.locator('[data-action="open-modal"][data-modal="custom"]').click();
    await page.locator('[data-field="customText"]').fill(name); await action(page,'apply-custom').click(); await screen(page,'game');
    await action(page,'launch').click(); await page.waitForSelector('[data-action="skip-animation"]'); await action(page,'skip-animation').click(); await screen(page,'result');
    assert.equal(await page.locator('[data-testid="destination-name"]').innerText(),name);
    await action(page,'expand-details').click();
    const guide=page.locator('[data-travel-guide]'); assert.ok(await guide.isVisible());
    return guide;
  }
  const guide = await draw('长沙');
  const city = DESTINATIONS.find(item=>item.id==='changsha');
  for (const food of city.foodGuide) assert.ok((await guide.innerText()).includes(food.description));
  assert.ok((await guide.innerText()).includes(city.travel));
  assert.ok((await guide.innerText()).includes(city.localTransport));
  assert.equal(await page.locator('.guide-itinerary li').count(),city.itinerary.length);
  await page.locator('.guide-sources summary').click();
  assert.equal(await page.locator('.guide-sources .source-link').count(),city.sources.length);
  assert.ok((await page.locator('.guide-sources').innerText()).includes('CC BY-SA 4.0'));
  const map = new URL(await page.locator('.travel-query-links a').first().getAttribute('href'));
  assert.equal(map.hostname,'uri.amap.com'); assert.equal(map.searchParams.get('keyword'),'长沙');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.equal(await guide.evaluate(el=>el.scrollWidth<=el.clientWidth+1),true);
  await mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/16-real-city-guide-mobile.png',fullPage:true});
  checks.push('city food explanations, arrival/local transport, itinerary, source attribution and map query');
  const spotGuide=await draw('橘子洲');
  assert.ok((await spotGuide.innerText()).includes('从所在城市怎么去'));
  assert.ok((await spotGuide.innerText()).includes('长沙可以吃什么'));
  assert.equal(await page.locator('.guide-itinerary').count(),0,'a half-day spot does not inherit a multi-day city itinerary');
  assert.doesNotMatch(await page.locator('.result-summary').innerText(),/¥\d+/);
  checks.push('spot-specific transport, correctly scoped food and no invented budget');
  const longPlace = DESTINATIONS.filter(item=>item.kind==='spot').sort((a,b)=>b.name.length-a.name.length)[0];
  await page.setViewportSize({width:320,height:760});
  await draw(longPlace.name);
  assert.equal(await page.locator('.postcard-copy').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  checks.push('long attraction names and guide content fit a narrow phone');
  await page.locator('[data-action="go"][data-screen="home"]').first().click();
  await page.locator('[data-action="open-modal"][data-modal="filters"]').first().click();
  await page.locator('[data-field="maxBudget"]').fill('500'); await action(page,'apply-filters').click();
  await page.locator('[data-action="select-preset"][data-id="explore"]').click(); await screen(page,'game');
  await page.locator('[data-action="open-modal"][data-modal="candidates"]').click();
  assert.equal(await page.locator('[data-candidate-name]').count(),0);
  assert.match(await page.locator('.candidate-rejections').innerText(),/暂无可靠消费区间/);
  checks.push('explicit budget excludes unknown costs with a clear reason');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:checks.length,checks},null,2));
} finally {await browser.close();await new Promise(resolve=>server.close(resolve));}
